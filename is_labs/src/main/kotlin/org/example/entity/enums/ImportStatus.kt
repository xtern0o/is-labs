package org.example.entity.enums

enum class ImportStatus {
    /**
     * Транзакция создана, работа с файлом езе не завершена
     */
    CREATED,

    /**
     * Файл загружен в minio и проверен через HEAD-запрос
     */
    FILE_STORED,

    /**
     * Файл разобран и предварительно провалидирован,
     * но еще не обработан
     */
    PREPARED,

    /**
     * Файл сохранен, все сущности сохранены в бд
     */
    SUCCESS,

    /**
     * Импорт прерван, объекты не созданы
     */
    FAILED,
}